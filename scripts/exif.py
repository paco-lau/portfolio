"""Writes app/lib/exif.ts: each photo's camera settings, shown in the gallery viewfinder.
Run after adding photos: python3 scripts/exif.py"""
import glob, os
from fractions import Fraction
from PIL import Image

lines = []
for f in sorted(glob.glob("assets/photography/**/*.jpg", recursive=True)):
    ex = Image.open(f).getexif().get_ifd(0x8769)
    mm, fn, t, iso = (ex.get(k) for k in (0x920A, 0x829D, 0x829A, 0x8827))
    if not (mm and fn and t and iso):
        continue
    t = float(t)
    shutter = f"{t:g}s" if t >= 1 else f"1/{round(1 / t)}s"
    name = os.path.basename(f).split(".")[0]
    lines.append(f'  "{name}": "{float(mm):g}mm · f/{float(fn):g} · {shutter} · ISO {iso}",')

with open("app/lib/exif.ts", "w") as out:
    out.write("// Generated by scripts/exif.py from each photo's EXIF; keyed by file name.\n")
    out.write("export const EXIF: Record<string, string> = {\n" + "\n".join(lines) + "\n};\n")
